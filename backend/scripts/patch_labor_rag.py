def run_patch():
    docs = [a["text"] for a in ARTICLES]
    metas = [a["metadata"] for a in ARTICLES]
    ids = [a["id"] for a in ARTICLES]

    print(f"Patching RAG with {len(ARTICLES)} critical labor code articles...")
    before = rag_service.collection.count()
    print(f"  Before: {before} documents")

    success = rag_service.add_documents(docs, metas, ids)
    if success:
        after = rag_service.collection.count()
        print(f"  After:  {after} documents (+{after - before})")
        print("  ✅ Patch applied successfully!")
    else:
        print("  ❌ Patch failed!")

    # Quick verification
    print("\nVerification — searching 'увольнение' keyword:")
    all_docs = rag_service.collection.get(include=["documents", "metadatas"])
    hits = [(doc, meta) for doc, meta in zip(all_docs["documents"], all_docs["metadatas"])
            if "увольнен" in doc.lower()]
    print(f"  Docs containing 'увольнен': {len(hits)}")
    for doc, meta in hits[:3]:
        print(f"    art={meta.get('article')}, source={meta.get('source')}, type={meta.get('type')}")

if __name__ == "__main__":
    run_patch()
